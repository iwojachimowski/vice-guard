import { stem } from './stem';
import { tokenize, BOUNDARY } from './normalize';

/** Phrases are stored as stemmed token lists so they match tokenized cards. */
export type Phrase = string[];
const phrases = (...list: string[]): Phrase[] =>
  list.map((text) =>
    tokenize(text)
      .filter((t) => t !== BOUNDARY)
      .map(stem),
  );

